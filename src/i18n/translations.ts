export function t(lang: Language, path: string): string {
  const keys = path.split('.');
  let current: Translations | string = translations[lang];
  for (const key of keys) {
    if (typeof current === 'string') return path;
    current = (current as Translations)[key];
    if (current === undefined) return path;
  }
  return typeof current === 'string' ? current : path;
}

// Helper to translate crop names
export function translateCrop(crop: string | null | undefined, lang: Language): string {
  if (!crop) return lang === 'ta' ? 'தெரியவில்லை' : 'Unknown';
  if (lang === 'en') return crop;
  
  const lower = crop.toLowerCase();
  if (lower.includes('corn') || lower.includes('maize')) return 'மக்காச்சோளம் (Corn)';
  if (lower.includes('grape')) return 'திராட்சை (Grape)';
  if (lower.includes('apple')) return 'ஆப்பிள் (Apple)';
  if (lower.includes('cherry')) return 'செர்ரி (Cherry)';
  if (lower.includes('blueberry')) return 'புளூபெர்ரி (Blueberry)';
  if (lower.includes('sugarcane')) return 'கரும்பு (Sugarcane)';
  if (lower.includes('paddy') || lower.includes('rice')) return 'நெல் (Paddy)';
  if (lower.includes('turmeric')) return 'மஞ்சள் (Turmeric)';
  if (lower.includes('banana')) return 'வாழை (Banana)';
  if (lower.includes('cotton')) return 'பருத்தி (Cotton)';
  if (lower.includes('tomato')) return 'தக்காளி (Tomato)';
  return crop;
}

// Helper to translate condition/disease names
export function translateCondition(condition: string | null | undefined, lang: Language): string {
  if (!condition) return lang === 'ta' ? 'செயலாக்கத்தில் உள்ளது' : 'Processing';
  if (lang === 'en') return condition;

  const lower = condition.toLowerCase();
  if (lower.includes('healthy')) return 'ஆரோக்கியமானது';
  if (lower.includes('cercospora') || lower.includes('gray_leaf_spot') || lower.includes('gray leaf spot'))
    return 'செர்கோஸ்போரா சாம்பல் இலைப்புள்ளி (Gray Leaf Spot)';
  if (lower.includes('common_rust') || lower.includes('common rust'))
    return 'சாமானிய துரு நோய் (Common Rust)';
  if (lower.includes('northern_leaf_blight') || lower.includes('northern leaf blight'))
    return 'வடக்கு இலை கருகல் நோய் (Northern Leaf Blight)';
  if (lower.includes('black_rot') || lower.includes('black rot'))
    return 'கரு அழுகல் நோய் (Black Rot)';
  if (lower.includes('esca') || lower.includes('black_measles') || lower.includes('black measles'))
    return 'எஸ்கா கருந்தட்டம் (Black Measles)';
  if (lower.includes('leaf_blight') || lower.includes('leaf blight') || lower.includes('isariopsis'))
    return 'இலை கருகல் நோய் (Isariopsis Blight)';
  if (lower.includes('apple_scab') || lower.includes('apple scab'))
    return 'ஆப்பிள் சொறி நோய் (Apple Scab)';
  if (lower.includes('cedar_apple_rust') || lower.includes('cedar apple rust'))
    return 'சிடார் ஆப்பிள் துரு நோய் (Cedar Rust)';
  if (lower.includes('powdery_mildew') || lower.includes('powdery mildew'))
    return 'வெண்பூஞ்சை நோய் (Powdery Mildew)';
  return condition;
}

// Helper to translate soil types
export function translateSoil(soil: string | null | undefined, lang: Language): string {
  if (!soil) return lang === 'ta' ? 'வண்டல் மண்' : 'Loamy';
  if (lang === 'en') return soil;
  const lower = soil.toLowerCase();
  if (lower === 'loamy') return 'வண்டல் மண் (Loamy)';
  if (lower === 'clay') return 'களிமண் (Clay)';
  if (lower === 'sandy') return 'மணல் மண் (Sandy)';
  if (lower === 'silt') return 'வண்டல் சேறு (Silt)';
  if (lower === 'peat') return 'மட்கிய மண் (Peat)';
  return soil;
}
